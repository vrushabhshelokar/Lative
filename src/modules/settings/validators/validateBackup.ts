export interface BackupValidationResult {
  isValid: boolean;
  error?: string;
}

/**
 * Validates the parsed contents of an imported Lative backup file.
 */
export function validateBackupData(data: unknown): BackupValidationResult {
  if (!data || typeof data !== 'object') {
    return { isValid: false, error: 'Backup is not a valid JSON object.' };
  }

  const obj = data as Record<string, unknown>;

  // 1. Check metadata
  if (!obj.metadata || typeof obj.metadata !== 'object') {
    return { isValid: false, error: 'Backup metadata is missing.' };
  }

  const metadata = obj.metadata as Record<string, unknown>;
  if (metadata.app !== 'Lative') {
    return { isValid: false, error: 'Incompatible file. Only backups generated by Lative are supported.' };
  }

  // Check version compatibility
  if (metadata.version !== '1.0') {
    return { isValid: false, error: `Incompatible backup version: ${metadata.version}` };
  }

  // 2. Check database presence
  if (!obj.database || typeof obj.database !== 'object') {
    return { isValid: false, error: 'Database section is missing in backup file.' };
  }

  const dbObj = obj.database as Record<string, unknown>;
  const requiredTables = ['resumes', 'parsedResumes', 'certificates', 'links', 'mails', 'carts'];
  for (const table of requiredTables) {
    if (!Array.isArray(dbObj[table])) {
      return { isValid: false, error: `Database table "${table}" is missing or invalid in backup file.` };
    }
  }

  // 3. Validate settings
  if (!obj.settings || typeof obj.settings !== 'object') {
    return { isValid: false, error: 'Settings section is missing in backup file.' };
  }

  return { isValid: true };
}

export default validateBackupData;
